import {cell, findingsTable} from '../core/reporters/markdown.js'
import {countBySeverity} from '../core/scoring.js'
import type {GateResult} from '../core/types.js'
import {TOOL_NAME, TOOL_VERSION} from '../core/version.js'
import {groupComponents} from './components.js'
import type {TestSummary} from './test-results.js'

export interface BriefInput {
  storyId: string
  gate: GateResult
  thresholds: {failOn: 'error' | 'warning'; maxRiskScore: number}
  /** Changed (scanned) files, repo-relative. */
  files: readonly string[]
  /** Files added by the change; a revert deployment does not delete them. */
  addedFiles: readonly string[]
  tests: TestSummary | null
  summary: string
  summarySource: 'ai' | 'template'
  generatedAt: Date
}

const short = (sha: string | null): string => (sha ? sha.slice(0, 10) : 'unknown')
const code = (text: string): string => `\`${text.replace(/`/g, "'")}\``

function changedComponents(files: readonly string[]): string[] {
  const c = groupComponents(files)
  const list = <T>(items: T[], render: (item: T) => string): string[] =>
    items.length ? items.map((item) => `- ${render(item)}`) : ['- None']
  return [
    `**Apex classes (${c.apexClasses.length})**`,
    '',
    ...list(c.apexClasses, (x) => `${code(x.name)} (${code(x.path)})`),
    '',
    `**Apex triggers (${c.triggers.length})**`,
    '',
    ...list(c.triggers, (x) => `${code(x.name)} (${code(x.path)})`),
    '',
    `**Lightning web components (${c.lwc.length})**`,
    '',
    ...list(c.lwc, (x) => `${code(x.name)}: ${x.files.map(code).join(', ')}`),
  ]
}

function testStatus(tests: TestSummary | null): string[] {
  if (!tests) {
    return [
      'Not provided. Run `sf apex run test --json > test-results.json` and pass `--test-results test-results.json`.',
    ]
  }
  const lines = [
    `- Outcome: **${tests.outcome}**`,
    `- Tests: ${tests.testsRan} ran, ${tests.passing} passed, ${tests.failing} failed, ${tests.skipped} skipped`,
  ]
  if (tests.orgWideCoverage) lines.push(`- Org-wide coverage: ${tests.orgWideCoverage}`)
  if (tests.testRunCoverage) lines.push(`- Test run coverage: ${tests.testRunCoverage}`)
  if (tests.failures.length) {
    lines.push('', '| Failed test | Message |', '|---|---|')
    for (const f of tests.failures.slice(0, 20))
      lines.push(`| ${cell(f.name)} | ${cell(f.message.slice(0, 300))} |`)
    if (tests.failures.length > 20) lines.push('', `_${tests.failures.length - 20} more failures not shown._`)
  }
  return lines
}

function rollbackPlan(input: BriefInput): string[] {
  const {gate, files, addedFiles, storyId} = input
  const lines = [
    gate.baseSha
      ? `- Base commit: ${code(gate.baseSha)} (${code(gate.baseRef)})`
      : '- Base commit: not known (scan was not run against a base branch).',
    `- Head commit: ${gate.headSha ? code(gate.headSha) : 'not known'}`,
    `- Changed files (${files.length}):`,
    ...files.map((f) => `  - ${code(f)}${addedFiles.includes(f) ? ' (added)' : ''}`),
    '',
    'Steps:',
    '',
    gate.baseSha && gate.headSha
      ? `1. Revert the change on a new branch: ${code(`git revert --no-edit ${short(gate.baseSha)}..${short(gate.headSha)}`)}. ` +
        `If it was already merged, revert the merge commit instead: ${code('git revert -m 1 <merge-commit>')}.`
      : '1. Revert the commits of this user story on a new branch with `git revert`.',
    `2. Re-run validation: ${code(`agentia guardian gate --story ${storyId}`)}, then ${code('agentia cicd work test')}.`,
    `3. Re-promote the revert through the pipeline: ${code('agentia cicd work submit')}.`,
  ]
  if (addedFiles.length) {
    lines.push(
      '',
      `Note: deploying a revert does not delete the ${addedFiles.length} added file(s) from the org. ` +
        'Remove them with a destructive change if they must go.',
    )
  }
  return lines
}

function gateResult(input: BriefInput): string[] {
  const {gate, thresholds} = input
  const c = countBySeverity(gate.findings)
  return [
    '| Check | Result |',
    '|---|---|',
    `| Gate | **${gate.passed ? 'PASSED' : 'FAILED'}** |`,
    `| Risk score | ${gate.riskScore}/100 (maximum allowed ${thresholds.maxRiskScore}) |`,
    `| Blocking findings | ${gate.blockingCount} (fail on ${thresholds.failOn} or higher) |`,
    `| Findings | ${c.error} errors, ${c.warning} warnings, ${c.info} info |`,
    `| Files scanned | ${gate.filesScanned} |`,
  ]
}

/** Assembles the release brief as Markdown. Deterministic for the same input. */
export function buildBrief(input: BriefInput): string {
  const {gate} = input
  return [
    `# Release brief: ${input.storyId}`,
    '',
    `Generated by ${TOOL_NAME} ${TOOL_VERSION} on ${input.generatedAt.toISOString()}, ` +
      `comparing ${code(gate.baseRef)} (${short(gate.baseSha)}) with ${code(gate.headRef)} (${short(gate.headSha)}).`,
    '',
    '## Summary',
    '',
    input.summary,
    '',
    input.summarySource === 'ai'
      ? '_Summary written by the Copado AI release agent from file names and finding counts. All other sections are generated from the scan._'
      : '_Summary generated from the scan results._',
    '',
    '## Changed components',
    '',
    ...changedComponents(input.files),
    '',
    '## Risk findings',
    '',
    findingsTable(gate.findings),
    '',
    '## Test status',
    '',
    ...testStatus(input.tests),
    '',
    '## Rollback plan',
    '',
    ...rollbackPlan(input),
    '',
    '## Gate result',
    '',
    ...gateResult(input),
    '',
  ].join('\n')
}
